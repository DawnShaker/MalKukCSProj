import { readFile, writeFile } from "node:fs/promises";
import { adaptLegacyData } from "../server/import.mjs";
const root = new URL("../", import.meta.url);
const migration = await readFile(
  new URL("supabase/migrations/202611180001_relational_accounts.sql", root),
  "utf8",
);
const source = adaptLegacyData(
  JSON.parse(
    await readFile(new URL("RealEstateAgency/agency_data.json", root), "utf8"),
  ),
);
const seed = JSON.stringify(source);
const delimiter = "$realestate_seed_20261118$";
if (seed.includes(delimiter))
  throw new Error("Unexpected SQL seed delimiter in input");
const core = migration.replace(/^begin;\s*$/m, "").replace(/commit;\s*$/, "");
const importer = `
-- Non-destructive, repeatable import of the repository's agency_data.json.
do $import_agency$
declare
  incoming jsonb := ${delimiter}${seed}${delimiter}::jsonb;
  snapshot jsonb; merged jsonb; collection text; additions jsonb;
begin
  perform 1 from public.agency_revision where id = 1 for update;
  snapshot := public.agency_read_snapshot();
  merged := snapshot->'data';
  foreach collection in array array['agents','clients','properties','deals','requests','searchHistory'] loop
    select coalesce(jsonb_agg(item.value), '[]') into additions
    from jsonb_array_elements(coalesce(incoming->collection, '[]')) item
    where not exists (
      select 1 from jsonb_array_elements(coalesce(merged->collection, '[]')) current
      where current.value->>'id' = item.value->>'id'
    ) and (collection <> 'deals' or not exists (
      select 1 from jsonb_array_elements(coalesce(merged->'deals','[]')) current
      where current.value->>'propertyId' = item.value->>'propertyId'
    ));
    merged := jsonb_set(merged, array[collection], coalesce(merged->collection,'[]') || additions);
  end loop;
  if merged <> snapshot->'data' then
    if not public.agency_save_snapshot((snapshot->>'version')::bigint, merged) then
      raise exception 'Concurrent migration change; retry setup.sql';
    end if;
  end if;
end $import_agency$;
commit;

select 'properties' as collection, count(*) as records from public.properties
union all select 'clients', count(*) from public.clients
union all select 'agents', count(*) from public.agents
union all select 'deals', count(*) from public.deals
union all select 'status_history', count(*) from public.property_status_history
union all select 'price_history', count(*) from public.property_price_history
union all select 'saved_searches', count(*) from public.saved_searches;
`;
await writeFile(
  new URL("supabase/setup.sql", root),
  `-- Generated by npm run db:prepare. Contains no API keys or account passwords.\n-- Run the WHOLE file in the SQL Editor of your existing Supabase project.\n-- The entire migration and data import are atomic. Existing IDs are preserved.\nbegin;\n${core}\n${importer}`,
  "utf8",
);
console.log(
  `Prepared supabase/setup.sql: ${source.properties.length} properties, ${source.clients.length} clients, ${source.agents.length} agents, ${source.deals.length} deals.`,
);
